import os
import re

from django.conf import settings
from rest_framework import serializers

from apps.folders.models import Folder

from .models import File


ALLOWED_EXTENSIONS = {
    ".pdf",
    ".jpg",
    ".jpeg",
    ".png",
    ".webp",
    ".docx",
    ".xlsx",
    ".txt",
}


ALLOWED_MIME_TYPES = {
    ".pdf": {"application/pdf"},
    ".jpg": {"image/jpeg"},
    ".jpeg": {"image/jpeg"},
    ".png": {"image/png"},
    ".webp": {"image/webp"},
    ".docx": {
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
    },
    ".xlsx": {
        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    },
    ".txt": {
        "text/plain",
    },
}


UNSAFE_FILENAME_CHARS = re.compile(
    r'[<>:"/\\|?*\x00-\x1f]'
)


def sanitize_filename(filename):
    """
    Sanitize a user-visible filename.

    This does NOT change the actual storage path generated by Django.
    It only protects the logical filename stored in the database.
    """

    filename = os.path.basename(filename)

    # Remove unsafe/control characters.
    filename = UNSAFE_FILENAME_CHARS.sub("_", filename)

    # Collapse repeated whitespace.
    filename = re.sub(r"\s+", " ", filename).strip()

    # Prevent empty / "." / ".." names.
    if filename in {"", ".", ".."}:
        raise serializers.ValidationError(
            "Invalid file name."
        )

    # Prevent problematic leading/trailing dots and spaces.
    filename = filename.strip(" .")

    if not filename:
        raise serializers.ValidationError(
            "Invalid file name."
        )

    return filename[:255]


